const KEEP_UPPER = new Set(['BIP', 'RGB', 'BOLT', 'NIP']);
// Noms affichés du livre (templates/parts.yaml, champ display), donnés par le build.
const AFFICHAGE = new Map();
export const setAffichage = (paires) => paires.forEach(([k, v]) => v && AFFICHAGE.set(k, v));
// « ÉCONOMIE ET RÉGULATION » -> « Économie et régulation ».
function labelFr(name) {
  if (AFFICHAGE.has(name)) return AFFICHAGE.get(name);
  if (KEEP_UPPER.has(name)) return name;
  if (name === 'BLIP') return 'bLIP';
  return name
    .toLocaleLowerCase('fr')
    .replace(/^./, (c) => c.toLocaleUpperCase('fr'))
    .replace(/lightning network/i, 'Lightning Network')
    .replace(/\bbitvm\b/i, 'BitVM')
    .replace(/\bbitcoin\b/, 'Bitcoin')
    .replace(/\bnostr\b/, 'Nostr')
    .replace(/\blightning\b/, 'Lightning')
    .replace(/\bspark\b/, 'Spark');
}

