export const LANGUES = { fr: FR, en: EN };

// Langue courante du build : le build écrit tout le français, puis tout l'anglais.
export let t = FR;
export function setLangue(code) {
  t = LANGUES[code];
  return t;
}

// ---------------------------------------------------------------- Chemins
// Un chemin de l'autre langue, pour le bouton FR / EN et les liens hreflang.
export const chemins = (L) => ({
  code: L.code,
  accueil: () => `${L.base}/`,
  def: (slug) => `${L.base}/${slug}/`,
  categorie: (cat) => `${L.base}/${L.seg.categorie}/${catSlug(cat, L)}/`,
  lettre: (l) => `${L.base}/${L.seg.lettre}/${l.toLowerCase()}/`,
  recherche: () => `${L.base}/${L.seg.recherche}/`,
  chronologie: () => `${L.base}/${L.seg.chronologie}/`,
  specs: (serie) => `${L.base}/${L.seg.specs}/${serie ? `${serie}/` : ''}`,
  partie: (id) => `${L.base}/${L.seg.partie}/${partieSlug(id, L)}/`,
});
export const lien = new Proxy({}, { get: (_, k) => chemins(t)[k] });

// Nom affiché d'une catégorie dans la langue courante (ou dans L).
// Apostrophe typographique, comme les titres (« Plateforme d’échange »).
export function categoryLabel(name, L = t) {
  if (L.code === 'en' && CATEGORIES_EN[name]) return CATEGORIES_EN[name].replace(/'/g, '’');
  return labelFr(name).replace(/'/g, '’');
}
// Slug d'une catégorie : le slug français (contrat d'URL), ou le nom anglais en anglais.
export function catSlug(cat, L = t) {
  if (L.code === 'en' && CATEGORIES_EN[cat.name]) return slugify(CATEGORIES_EN[cat.name]);
  return cat.slug;
}
const PARTIE_SLUG_EN = { technique: 'technical', ecosysteme: 'ecosystem', personnes: 'people', specifications: 'specifications' };
export const partieSlug = (id, L = t) => (L.code === 'en' ? PARTIE_SLUG_EN[id] || id : id);
// Noms des séries de spécifications présentes : « BIP, BOLT et bLIP » / « BIPs, BOLTs and bLIPs ».
const NOM_SERIE = { bip: 'BIP', bolt: 'BOLT', blip: 'bLIP', nip: 'NIP' };
export const nomsSeries = (ids, L = t) => new Intl.ListFormat(L.locale, { type: 'conjunction' }).format(ids.map((id) => (NOM_SERIE[id] || id.toUpperCase()) + (L.code === 'en' ? 's' : '')));
export const partieTitre = (p, L = t) => (L.code === 'en' && PARTIES_EN[p.id] ? PARTIES_EN[p.id].title : p.title);
export const partieIntro = (p, L = t) => (L.code === 'en' && PARTIES_EN[p.id] ? PARTIES_EN[p.id].intro : p.intro || '');
